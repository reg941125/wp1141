import { ObjectId, type Filter } from "mongodb";

import { getTodosCollection, todoSchema, type TodoDocument } from "@/lib/db";
import type { StructuredTodo, TodoPriority, TodoStatus } from "@/lib/llm/types";
import { logger } from "@/lib/logger";
import {
  inferCategory,
  inferDueDate,
  inferPriority,
  inferRemindAt,
  inferStatus,
} from "@/lib/todos/inference";
import {
  getAssistantSettings,
  type AssistantSettings,
} from "@/lib/settings/service";
import { publishAdminEvent } from "@/lib/realtime/bus";

type ApplyTodoOperationsInput = {
  userId: string;
  sessionId: string;
  sourceMessageId?: string;
  tasks: StructuredTodo[];
};

export type TodoMutationResult = {
  action: "created" | "updated" | "archived" | "deleted" | "skipped";
  title: string;
  todoId?: string;
  reason?: string;
};

const parseDate = (value?: string) => {
  if (!value) {
    return undefined;
  }
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return undefined;
  }
  return date;
};

const computeDefaultReminder = (
  settings: AssistantSettings,
  dueDate?: Date | null,
) => {
  if (settings.defaultReminderLeadHours <= 0) {
    return undefined;
  }
  const base = dueDate ?? new Date();
  const reminder = new Date(base);
  reminder.setHours(reminder.getHours() - settings.defaultReminderLeadHours);
  return reminder;
};

const buildTodoFields = (
  task: StructuredTodo,
  input: Pick<ApplyTodoOperationsInput, "userId" | "sessionId" | "sourceMessageId">,
  settings: AssistantSettings,
) => {
  const inferredStatus = inferStatus(task.title);
  const dueDate = parseDate(task.dueDate) ?? inferDueDate(task.title);
  const remindAt =
    parseDate(task.remindAt) ??
    inferRemindAt(dueDate ?? undefined) ??
    computeDefaultReminder(settings, dueDate ?? undefined);

  const metadata: Record<string, unknown> = {};
  if (task.inferredFrom) {
    metadata.inferredFrom = task.inferredFrom;
  }
  if (input.sourceMessageId) {
    metadata.sourceMessageId = input.sourceMessageId;
  }

  return {
    userId: input.userId,
    sessionId: input.sessionId,
    title: task.title.trim(),
    description: task.description,
    category: task.category ?? inferCategory(task.title),
    priority: task.priority ?? inferPriority(task.title),
    status: task.status ?? inferredStatus ?? "pending",
    dueDate: dueDate ?? null,
    remindAt: remindAt ?? null,
    autoGenerated: true,
    blockingReason: undefined,
    subtasks: (task.subtasks ?? []).map((subtask) => ({
      title: subtask.title,
      status: subtask.status ?? "pending",
    })),
    contexts: task.contexts ?? [],
    metadata: Object.keys(metadata).length ? metadata : undefined,
  } satisfies Omit<
    TodoDocument,
    "_id" | "createdAt" | "updatedAt" | "autoGenerated"
  > & { autoGenerated: boolean };
};

const findExistingTodo = async (
  task: StructuredTodo,
  input: ApplyTodoOperationsInput,
) => {
  const todos = await getTodosCollection();
  if (task.clientId) {
    try {
      const objectId = new ObjectId(task.clientId);
      return await todos.findOne({
        _id: objectId,
        userId: input.userId,
      });
    } catch (error) {
      logger.warn("Invalid todo clientId, fallback to title matching", {
        clientId: task.clientId,
        error,
      });
    }
  }

  return todos.findOne({
    userId: input.userId,
    title: task.title.trim(),
  });
};

export const applyTodoOperations = async (
  input: ApplyTodoOperationsInput,
): Promise<TodoMutationResult[]> => {
  const todos = await getTodosCollection();
  const now = new Date();
  const results: TodoMutationResult[] = [];
  const settings = await getAssistantSettings();

  for (const task of input.tasks) {
    try {
      const fields = buildTodoFields(task, input, settings);
      const existing = await findExistingTodo(task, input);

      if (!existing) {
        const doc = todoSchema.parse({
          ...fields,
          createdAt: now,
          updatedAt: now,
        });
        const insertResult = await todos.insertOne(doc);
        results.push({
          action: "created",
          title: task.title,
          todoId: insertResult.insertedId.toString(),
        });
        publishAdminEvent({
          type: "todo.mutation",
          payload: {
            userId: input.userId,
            sessionId: input.sessionId,
            mutation: results[results.length - 1],
          },
        });
        continue;
      }

      await todos.updateOne(
        { _id: existing._id },
        {
          $set: {
            ...fields,
            createdAt: existing.createdAt ?? now,
            updatedAt: new Date(),
          },
        },
      );

      results.push({
        action: fields.status === "archived" ? "archived" : "updated",
        title: task.title,
        todoId: existing._id?.toString(),
      });
      publishAdminEvent({
        type: "todo.mutation",
        payload: {
          userId: input.userId,
          sessionId: input.sessionId,
          mutation: results[results.length - 1],
        },
      });
    } catch (error) {
      logger.error("Failed to process todo task", { task, error });
      results.push({
        action: "skipped",
        title: task.title,
        reason: error instanceof Error ? error.message : "unknown error",
      });
    }
  }

  return results;
};

type TodoListFilters = {
  userId?: string;
  search?: string;
  status?: TodoStatus | "active";
  priority?: TodoPriority[];
  limit?: number;
  offset?: number;
};

export const listTodos = async (filters: TodoListFilters = {}) => {
  const todos = await getTodosCollection();
  const query: Filter<TodoDocument> = {};

  if (filters.userId) {
    query.userId = filters.userId;
  }

  if (filters.status) {
    if (filters.status === "active") {
      query.status = { $in: ["pending", "in_progress"] };
    } else {
      query.status = filters.status;
    }
  }

  if (filters.priority?.length) {
    query.priority = { $in: filters.priority };
  }

  if (filters.search) {
    query.title = { $regex: filters.search, $options: "i" };
  }

  const limit = Math.min(filters.limit ?? 50, 200);
  const offset = filters.offset ?? 0;

  return todos
    .find(query)
    .sort({ updatedAt: -1 })
    .skip(offset)
    .limit(limit)
    .toArray();
};

type CreateTodoInput = Pick<ApplyTodoOperationsInput, "userId" | "sessionId"> & {
  title: string;
  description?: string;
  status?: TodoStatus;
  priority?: TodoPriority;
  dueDate?: string;
  remindAt?: string;
  category?: string;
  contexts?: string[];
  subtasks?: StructuredTodo["subtasks"];
};

export const createTodo = async (input: CreateTodoInput) => {
  const todos = await getTodosCollection();
  const settings = await getAssistantSettings();
  const now = new Date();

  const normalized = buildTodoFields(
    {
      title: input.title,
      description: input.description,
      status: input.status,
      priority: input.priority,
      dueDate: input.dueDate,
      remindAt: input.remindAt,
      category: input.category,
      contexts: input.contexts,
      subtasks: input.subtasks,
    },
    { ...input, sourceMessageId: undefined },
    settings,
  );

  const doc = todoSchema.parse({
    ...normalized,
    createdAt: now,
    updatedAt: now,
    autoGenerated: false,
  });

  const result = await todos.insertOne(doc);
  const created = { ...doc, _id: result.insertedId };
  publishAdminEvent({
    type: "todo.mutation",
    payload: {
      userId: input.userId,
      sessionId: input.sessionId,
      mutation: {
        action: "created",
        title: input.title,
        todoId: result.insertedId.toString(),
      },
    },
  });
  return created;
};

type UpdateTodoInput = {
  todoId: string;
  updates: Partial<
    Pick<
      TodoDocument,
      | "title"
      | "description"
      | "status"
      | "priority"
      | "dueDate"
      | "remindAt"
      | "category"
      | "contexts"
      | "subtasks"
    >
  >;
};

export const updateTodo = async ({ todoId, updates }: UpdateTodoInput) => {
  const todos = await getTodosCollection();
  const objectId = new ObjectId(todoId);

  const safeUpdates: Partial<TodoDocument> = { ...updates };
  if (typeof updates.dueDate === "string") {
    safeUpdates.dueDate = parseDate(updates.dueDate) ?? null;
  }
  if (typeof updates.remindAt === "string") {
    safeUpdates.remindAt = parseDate(updates.remindAt) ?? null;
  }

  const result = await todos.findOneAndUpdate(
    { _id: objectId },
    {
      $set: {
        ...safeUpdates,
        updatedAt: new Date(),
      },
    },
    { returnDocument: "after" },
  );

  if (!result || !result.value) {
    throw new Error("Todo not found");
  }

  publishAdminEvent({
    type: "todo.mutation",
    payload: {
      userId: result.value.userId,
      sessionId: result.value.sessionId,
      mutation: {
        action: updates.status === "archived" ? "archived" : "updated",
        title: result.value.title,
        todoId: result.value._id?.toString(),
      },
    },
  });

  return result.value;
};

export const deleteTodo = async (todoId: string) => {
  const todos = await getTodosCollection();
  const objectId = new ObjectId(todoId);
  const existing = await todos.findOne({ _id: objectId });
  await todos.deleteOne({ _id: objectId });
  if (existing) {
    publishAdminEvent({
      type: "todo.mutation",
      payload: {
        userId: existing.userId,
        sessionId: existing.sessionId,
        mutation: {
          action: "deleted",
          title: existing.title,
          todoId: existing._id?.toString(),
        },
      },
    });
  }
};

