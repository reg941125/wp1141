import { ObjectId } from "mongodb";
import { z } from "zod";

const objectIdSchema = z.instanceof(ObjectId);

export const userSchema = z.object({
  _id: objectIdSchema.optional(),
  lineUserId: z.string(),
  displayName: z.string().optional(),
  pictureUrl: z.string().url().optional(),
  language: z.string().optional(),
  timeZone: z.string().optional(),
  metadata: z.record(z.unknown()).optional(),
  createdAt: z.date().default(() => new Date()),
  updatedAt: z.date().default(() => new Date()),
});

export const sessionSchema = z.object({
  _id: objectIdSchema.optional(),
  userId: z.string(),
  sessionId: z.string(),
  channel: z.enum(["line"]),
  startedAt: z.date().default(() => new Date()),
  lastActivityAt: z.date().default(() => new Date()),
  updatedAt: z.date().default(() => new Date()),
  tags: z.array(z.string()).default([]),
  metadata: z.record(z.unknown()).optional(),
});

export const todoSchema = z.object({
  _id: objectIdSchema.optional(),
  userId: z.string(),
  sessionId: z.string(),
  title: z.string(),
  description: z.string().optional(),
  category: z.string().optional(),
  priority: z.enum(["urgent", "high", "medium", "low"]).default("medium"),
  status: z
    .enum(["pending", "in_progress", "completed", "archived"])
    .default("pending"),
  dueDate: z.date().nullable().optional(),
  remindAt: z.date().nullable().optional(),
  autoGenerated: z.boolean().default(false),
  blockingReason: z.string().optional(),
  subtasks: z
    .array(
      z.object({
        title: z.string(),
        status: z.enum(["pending", "completed"]).default("pending"),
      }),
    )
    .default([]),
  contexts: z.array(z.string()).default([]),
  metadata: z.record(z.unknown()).optional(),
  createdAt: z.date().default(() => new Date()),
  updatedAt: z.date().default(() => new Date()),
});

export const messageSchema = z.object({
  _id: objectIdSchema.optional(),
  eventId: z.string(),
  userId: z.string(),
  sessionId: z.string(),
  direction: z.enum(["inbound", "outbound"]),
  channel: z.enum(["line"]),
  type: z.enum(["text", "template", "flex", "richmenu", "system"]).default("text"),
  payload: z.record(z.unknown()),
  llmLatencyMs: z.number().optional(),
  llmModel: z.string().optional(),
  llmUsageTokens: z
    .object({
      prompt: z.number().optional(),
      completion: z.number().optional(),
      total: z.number().optional(),
    })
    .optional(),
  metadata: z.record(z.unknown()).optional(),
  createdAt: z.date().default(() => new Date()),
});

export const assistantSettingsSchema = z.object({
  _id: objectIdSchema.optional(),
  key: z.literal("assistant"),
  defaultPriority: z.enum(["urgent", "high", "medium", "low"]).default("medium"),
  defaultReminderLeadHours: z.number().min(0).max(168).default(2),
  updatedAt: z.date().default(() => new Date()),
});

export const adminLogSchema = z.object({
  _id: objectIdSchema.optional(),
  level: z.enum(["info", "warn", "error"]).default("info"),
  message: z.string(),
  context: z.record(z.unknown()).optional(),
  createdAt: z.date().default(() => new Date()),
});

export type UserDocument = z.infer<typeof userSchema>;
export type SessionDocument = z.infer<typeof sessionSchema>;
export type TodoDocument = z.infer<typeof todoSchema>;
export type MessageDocument = z.infer<typeof messageSchema>;
export type AssistantSettingsDocument = z.infer<typeof assistantSettingsSchema>;
export type AdminLogDocument = z.infer<typeof adminLogSchema>;

